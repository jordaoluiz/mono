'use strict';
// Ponte mínima e explícita: a interface só enxerga estas funções.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('mono', {
  load: () => ipcRenderer.invoke('store:load'),
  save: (data) => ipcRenderer.invoke('store:save', data),
  send: (req, vars) => ipcRenderer.invoke('http:send', req, vars),
  curl: (req, vars) => ipcRenderer.invoke('http:curl', req, vars),
  preview: (html, baseUrl) => ipcRenderer.invoke('preview:create', html, baseUrl),
  setTheme: (name) => ipcRenderer.invoke('window:theme', name),
  applySettings: (settings) => ipcRenderer.invoke('settings:apply', settings),
  resolveProxy: (url) => ipcRenderer.invoke('proxy:resolve', url),
  saveFile: (opts) => ipcRenderer.invoke('file:save', opts),
  openFile: (opts) => ipcRenderer.invoke('file:open', opts),
  revealFile: (p) => ipcRenderer.invoke('file:reveal', p),
  pickFile: (opts) => ipcRenderer.invoke('file:pick', opts),
  inspectCert: (opts) => ipcRenderer.invoke('cert:inspect', opts),
  signXml: (opts) => ipcRenderer.invoke('xml:sign', opts),
  verifyXml: (xml) => ipcRenderer.invoke('xml:verify', xml),
  ai: (opts) => ipcRenderer.invoke('ai:complete', opts),
  secureStorage: () => ipcRenderer.invoke('crypto:available'),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: (cb) => { const fn = (_e, s) => cb(s); ipcRenderer.on('update:status', fn); return () => ipcRenderer.removeListener('update:status', fn); },
  realtime: {
    connect: (opts) => ipcRenderer.invoke('rt:connect', opts),
    send: (opts) => ipcRenderer.invoke('rt:send', opts),
    close: (opts) => ipcRenderer.invoke('rt:close', opts),
    onEvent: (cb) => { const fn = (_e, p) => cb(p); ipcRenderer.on('rt:event', fn); return () => ipcRenderer.removeListener('rt:event', fn); },
  },
  mock: {
    start: (opts) => ipcRenderer.invoke('mock:start', opts),
    update: (opts) => ipcRenderer.invoke('mock:update', opts),
    stop: () => ipcRenderer.invoke('mock:stop'),
    status: () => ipcRenderer.invoke('mock:status'),
    onHit: (cb) => { const fn = (_e, p) => cb(p); ipcRenderer.on('mock:hit', fn); return () => ipcRenderer.removeListener('mock:hit', fn); },
  },
  cloud: {
    call: (opts) => ipcRenderer.invoke('cloud:call', opts),
    connect: (opts) => ipcRenderer.invoke('cloud:connect', opts),
    disconnect: () => ipcRenderer.invoke('cloud:disconnect'),
    defaultUrl: () => ipcRenderer.invoke('cloud:defaultUrl'),
    onEvent: (cb) => { const fn = (_e, p) => cb(p); ipcRenderer.on('cloud:event', fn); return () => ipcRenderer.removeListener('cloud:event', fn); },
    onState: (cb) => { const fn = (_e, p) => cb(p); ipcRenderer.on('cloud:state', fn); return () => ipcRenderer.removeListener('cloud:state', fn); },
  },
  platform: process.platform,
});
